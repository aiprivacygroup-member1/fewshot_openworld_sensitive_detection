def find_video_files(input_path):
    """Find all video files in a directory or return a single file."""
    input_path = Path(input_path)
    if input_path.is_file():
        return [input_path] if input_path.suffix.lower() in VIDEO_EXTENSIONS else []
    if input_path.is_dir():
        videos = []
        for ext in VIDEO_EXTENSIONS:
            videos.extend(input_path.rglob(f'*{ext}'))
            videos.extend(input_path.rglob(f'*{ext.upper()}'))
        return sorted(videos)
    return []


def _extract_face_detections(results, conf_threshold=0.5):
    """Extract face detection boxes from YOLO results."""
    detections = []
    for result in results:
        if result.boxes is None:
            continue
        boxes = result.boxes.xyxy.cpu().numpy()
        cls_ids = result.boxes.cls.cpu().numpy().astype(int)
        confs = result.boxes.conf.cpu().numpy()
        for box, cls_id, conf in zip(boxes, cls_ids, confs):
            if cls_id == FACE_CLASS_ID and conf >= conf_threshold:
                detections.append({
                    'bbox': [float(v) for v in box],
                    'confidence': float(conf),
                })
    return detections


@torch.no_grad()
def process_video(detection_model, simswap_generator, video_path, output_path,
                  conf_threshold=0.5, crop_size=224, frame_skip=1,
                  device='cuda', show_progress=True):
    """Process a single video: detect faces → replace with synthetic faces.

    Args:
        detection_model: YOLO model for face detection.
        simswap_generator: SimSwapGenerator for face replacement.
        video_path: input video path.
        output_path: output video path.
        conf_threshold: minimum detection confidence.
        crop_size: face alignment/swap resolution (224 or 512).
        frame_skip: process every Nth frame.
        device: 'cuda' or 'cpu'.
        show_progress: print progress messages.

    Returns:
        dict with processing statistics.
    """
    cap = cv2.VideoCapture(str(video_path))
    if not cap.isOpened():
        raise ValueError(f"Cannot open video: {video_path}")

    orig_w = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    orig_h = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    fps = cap.get(cv2.CAP_PROP_FPS)
    total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))

    out_fps = fps / frame_skip if frame_skip > 1 else fps
    fourcc = cv2.VideoWriter_fourcc(*'mp4v')
    out = cv2.VideoWriter(str(output_path), fourcc, out_fps, (orig_w, orig_h))

    if show_progress:
        print(f"\nProcessing: {Path(video_path).name}")
        print(f"  Resolution: {orig_w}x{orig_h}, FPS: {fps:.1f}, "
              f"Frames: {total_frames}")

    # Fixed random identity latent for all faces in this video
    fixed_latent = torch.randn(1, 512, device=device)
    fixed_latent = fixed_latent / fixed_latent.norm(p=2, dim=1, keepdim=True)

    stats = {
        'video': str(video_path),
        'total_frames': 0,
        'processed_frames': 0,
        'total_faces_detected': 0,
        'total_faces_replaced': 0,
    }

    frame_idx = 0
    while True:
        ret, frame = cap.read()
        if not ret:
            break

        stats['total_frames'] += 1

        if frame_idx % frame_skip != 0:
            frame_idx += 1
            continue

        stats['processed_frames'] += 1

        # Step 1: YOLO face detection
        results = detection_model.predict(
            frame, device=device, conf=conf_threshold, iou=0.5,
            verbose=False, imgsz=640)
        face_dets = _extract_face_detections(results, conf_threshold)
        stats['total_faces_detected'] += len(face_dets)

        # Step 2: For each face, replace with synthetic face
        for det in face_dets:
            x1, y1, x2, y2 = [int(v) for v in det['bbox']]
            # Expand bbox slightly to include full face
            bw, bh = x2 - x1, y2 - y1
            x1 = max(0, x1 - int(0.1 * bw))
            y1 = max(0, y1 - int(0.2 * bh))
            x2 = min(orig_w, x2 + int(0.1 * bw))
            y2 = min(orig_h, y2 + int(0.1 * bh))

            face_crop = frame[y1:y2, x1:x2]

            if face_crop.size == 0:
                continue

            # Estimate landmarks from expanded bbox
            landmarks = _estimate_landmarks_from_bbox(x1, y1, x2, y2)

            # Align face to canonical pose
            aligned, M = _align_face(frame, landmarks, crop_size)

            # Run through SimSwap generator
            tensor_in = torch.from_numpy(
                aligned.transpose(2, 0, 1)).float().div(255.0).unsqueeze(0).to(device)
            swapped_tensor = simswap_generator(tensor_in, fixed_latent)
            swapped_face = swapped_tensor.squeeze(0).cpu().numpy().transpose(1, 2, 0)

            # Blend back into frame
            frame = _inverse_blend(swapped_face, M, crop_size, frame)
            stats['total_faces_replaced'] += 1

        out.write(frame)

        if show_progress and stats['processed_frames'] % 100 == 0:
            pct = frame_idx / total_frames * 100 if total_frames > 0 else 0
            print(f"  [{frame_idx}/{total_frames}] {pct:.0f}% "
                  f"| faces: {stats['total_faces_detected']}")

        frame_idx += 1

    cap.release()
    out.release()

    return stats


