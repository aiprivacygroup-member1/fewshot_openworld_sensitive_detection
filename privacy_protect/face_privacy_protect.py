# Canonical 5-point facial landmarks (FFHQ template, 512px → scaled to crop_size)
FFHQ_LANDMARKS_512 = np.array([
    [192.98138, 239.94708],   # left eye
    [318.90277, 240.1936],    # right eye
    [256.63416, 314.01935],   # nose
    [201.26117, 371.41043],   # left mouth corner
    [313.08905, 371.15118],   # right mouth corner
], dtype=np.float32)


