def main():
    parser = argparse.ArgumentParser(
        description='Face Privacy Protection — YOLO Detection + SimSwap Replacement',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python face_privacy_protect.py \\
      --detection_model output/models/detection/best.pt \\
      --simswap_model model/weights/90000_net_G.pth \\
      --input data/video/protect/

  python face_privacy_protect.py \\
      --detection_model best.pt \\
      --simswap_model 90000_net_G.pth \\
      --input data/video/protect/scene.mp4 \\
      --crop_size 224 --frame_skip 2
        """)

    parser.add_argument('--detection_model', type=str, required=True,
                        help='Path to trained YOLO detection model (.pt)')
    parser.add_argument('--simswap_model', type=str, required=True,
                        help='Path to SimSwap generator checkpoint (90000_net_G.pth)')
    parser.add_argument('--input', type=str, default='data/video/protect',
                        help='Video file or directory (default: data/video/protect/)')
    parser.add_argument('--output_dir', type=str, default='output/protected_videos')
    parser.add_argument('--conf_threshold', type=float, default=0.5,
                        help='Face detection confidence threshold (default: 0.5)')
    parser.add_argument('--crop_size', type=int, default=224,
                        choices=[224, 512],
                        help='Face alignment/swap size (default: 224)')
    parser.add_argument('--frame_skip', type=int, default=1,
                        help='Process every Nth frame (default: 1)')
    parser.add_argument('--device', type=str, default='cuda')

    args = parser.parse_args()

    if not ULTRALYTICS_AVAILABLE:
        print("ERROR: ultralytics not installed. Run: pip install ultralytics")
        sys.exit(1)

    try:
        from skimage import transform  # noqa: F401
    except ImportError:
        print("ERROR: scikit-image not installed. Run: pip install scikit-image")
        sys.exit(1)

    input_path = Path(args.input)
    if not input_path.exists():
        print(f"ERROR: Input not found: {args.input}")
        sys.exit(1)

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    videos = find_video_files(args.input)
    if not videos:
        print(f"No video files found in: {args.input}")
        sys.exit(1)

    print(f"\n{'='*60}")
    print("FACE PRIVACY PROTECTION")
    print(f"{'='*60}")
    print(f"  Detection model:  {args.detection_model}")
    print(f"  SimSwap model:    {args.simswap_model}")
    print(f"  Videos to process: {len(videos)}")
    print(f"  Crop size:        {args.crop_size}")
    print(f"  Confidence:       {args.conf_threshold}")
    print(f"  Frame skip:       {args.frame_skip}")

    # Load models (once)
    print(f"\nLoading detection model: {args.detection_model}")
    det_model = load_detection_model(args.detection_model, args.device)

    print(f"Loading SimSwap generator: {args.simswap_model}")
    gen = load_simswap_generator(args.simswap_model, args.crop_size, args.device)

    # Process each video
    start_time = datetime.now()
    all_stats = []

    for i, vid in enumerate(videos):
        stem = vid.stem
        if args.frame_skip > 1:
            stem += f"_skip{args.frame_skip}"
        stem += "_protected_face"
        output_path = output_dir / f"{stem}.mp4"

        print(f"\n[{i+1}/{len(videos)}] {vid.name}")
        try:
            stats = process_video(
                detection_model=det_model,
                simswap_generator=gen,
                video_path=vid,
                output_path=output_path,
                conf_threshold=args.conf_threshold,
                crop_size=args.crop_size,
                frame_skip=args.frame_skip,
                device=args.device,
            )
            all_stats.append(stats)
            print(f"  Done! {stats['total_faces_replaced']} faces replaced "
                  f"over {stats['processed_frames']} frames")
            print(f"  Saved: {output_path}")
        except Exception as e:
            print(f"  ERROR: {e}")
            continue

    elapsed = datetime.now() - start_time
    total_faces = sum(s['total_faces_replaced'] for s in all_stats)
    total_frames = sum(s['processed_frames'] for s in all_stats)

    print(f"\n{'='*60}")
    print("PROCESSING COMPLETE")
    print(f"{'='*60}")
    print(f"  Videos processed:  {len(all_stats)}")
    print(f"  Total frames:      {total_frames}")
    print(f"  Faces replaced:    {total_faces}")
    print(f"  Processing time:   {elapsed}")
    print(f"  Output directory:  {output_dir}")


if __name__ == '__main__':
    main()
