# ==============================================================================
# Landmark Estimation from BBox
# ==============================================================================

def _estimate_landmarks_from_bbox(x1, y1, x2, y2):
    """Estimate 5 facial landmarks from a face bounding box.

    Uses canonical face proportions to approximate landmark positions:
      - Left eye:   30% from left, 35% from top
      - Right eye:  70% from left, 35% from top
      - Nose:       50% from left, 55% from top
      - Left mouth: 35% from left, 75% from top
      - Right mouth: 65% from left, 75% from top
    """
    w, h = x2 - x1, y2 - y1
    return np.array([
        [x1 + 0.30 * w, y1 + 0.35 * h],  # left eye
        [x1 + 0.70 * w, y1 + 0.35 * h],  # right eye
        [x1 + 0.50 * w, y1 + 0.55 * h],  # nose
        [x1 + 0.35 * w, y1 + 0.75 * h],  # left mouth
        [x1 + 0.65 * w, y1 + 0.75 * h],  # right mouth
    ], dtype=np.float32)


# ==============================================================================
# Face Alignment
# ==============================================================================

def _estimate_norm(lmk, image_size=224):
    """Compute best-fit similarity transform from landmarks to FFHQ template."""
    from skimage import transform as trans

    src = FFHQ_LANDMARKS_512 * image_size / 512.0  # scale template to crop_size
    tform = trans.SimilarityTransform()
    lmk_tran = np.insert(lmk, 2, values=np.ones(5), axis=1)

    min_M = None
    min_error = float('inf')
    for i in range(src.shape[0]):
        tform.estimate(lmk, src[i])
        M = tform.params[0:2, :]
        results = np.dot(M, lmk_tran.T).T
        error = np.sum(np.sqrt(np.sum((results - src[i]) ** 2, axis=1)))
        if error < min_error:
            min_error = error
            min_M = M
    return min_M


def _align_face(img, landmarks, crop_size=224):
    """Align a face using 5-point landmarks → similarity transform → crop."""
    M = _estimate_norm(landmarks, crop_size)
    if M is None:
        # Fallback: simple resize crop
        return cv2.resize(img, (crop_size, crop_size)), np.eye(2, 3, dtype=np.float32)
    warped = cv2.warpAffine(img, M, (crop_size, crop_size), borderValue=0.0)
    return warped, M


# ==============================================================================
# Inverse Alignment + Blending
# ==============================================================================

def _inverse_blend(swapped_face, M, crop_size, ori_img):
    """Warp swapped face back to original image and blend with soft mask."""
    # Inverse affine matrix
    mat_rev = np.zeros([2, 3], dtype=np.float32)
    div = M[0][0] * M[1][1] - M[0][1] * M[1][0]
    if abs(div) < 1e-8:
        return ori_img  # degenerate matrix, skip
    mat_rev[0][0] = M[1][1] / div
    mat_rev[0][1] = -M[0][1] / div
    mat_rev[0][2] = -(M[0][2] * M[1][1] - M[0][1] * M[1][2]) / div
    div2 = M[0][1] * M[1][0] - M[0][0] * M[1][1]
    mat_rev[1][0] = M[1][0] / div2
    mat_rev[1][1] = -M[0][0] / div2
    mat_rev[1][2] = -(M[0][2] * M[1][0] - M[0][0] * M[1][2]) / div2

    ori_size = (ori_img.shape[1], ori_img.shape[0])

    # Warp swapped face back
    swapped_bgr = (swapped_face * 255).astype(np.uint8)
    target = cv2.warpAffine(swapped_bgr, mat_rev, ori_size)

    # Create soft mask
    mask_white = np.full((crop_size, crop_size), 255, dtype=np.float32)
    mask = cv2.warpAffine(mask_white, mat_rev, ori_size)
    mask[mask > 20] = 255

    kernel = np.ones((20, 20), np.uint8)
    mask = cv2.erode(mask, kernel, iterations=1)
    blur_size = (21, 21)
    mask = cv2.GaussianBlur(mask, blur_size, 0)
    mask = mask[:, :, np.newaxis] / 255.0

    result = (mask * target.astype(np.float32) +
              (1 - mask) * ori_img.astype(np.float32))
    return result.astype(np.uint8)


